//! 【本文件职责】本文件提供：**偏移表** —— 所有数据在内存里的位置（ESP 的“地图”）。
//!
//! 偏移表（AssaultCube 1.2.0.2，32 位进程）。
//!
//! # 偏移是什么
//! 游戏里的数据都在固定的位置上，用 Cheat Engine 扫出来的地址减去模块基址，
//! 得到的就是「偏移」。运行时：
//!
//! ```text
//! 绝对地址 = 模块基址(GetModuleHandleA) + 偏移
//! ```
//!
//! 用偏移而不是写死绝对地址，是因为游戏每次启动基址都可能不一样（ASLR）。
//!
//! # 怎么找这些偏移（思路）
//! 1. CE 里搜自己血量 → 找到地址 → 右键「找出是什么改写了这个地址」→ 追出基址；
//! 2. 得到基址后，用「基址 + 偏移」的形式记录，重启游戏验证一次；
//! 3. 坐标这类浮点数，用「未知初始值 → 走动一下 → 变大了/变小了」逐步筛选。
//!
//! # 关于 `Option<usize>`
//! 没验证过的偏移写成 `None`：程序会自动降级（关掉对应功能），
//! 而不是拿一个猜的数字读到垃圾数据、让人以为"这段代码坏了"。
//! 你扫到正确值以后把 `None` 改成 `Some(0x????)` 即可。

// ---------------------------------------------------------------------------
// 全局静态偏移（相对模块基址）
// ---------------------------------------------------------------------------

/// 当前玩家数量（u32）。
pub const PLAYER_COUNT: usize = 0x18AC0C;

/// 视图矩阵（4x4 的 f32，共 64 字节，列主序，和 OpenGL 一致）。
/// 「世界坐标 → 屏幕坐标」全靠它，可以说是 ESP 的眼睛。
pub const VIEW_MATRIX: usize = 0x17DFD0;

/// 实体列表：从 `基址 + ENTITY_LIST` 开始是一段连续的 `entity*` 指针数组。
/// 第 i 个元素的地址 = 基址 + ENTITY_LIST + i * 4，元素内容才是实体结构体的地址。
/// 记住这里是「指针的数组」，所以要多解一层引用。
pub const ENTITY_LIST: usize = 0x18AC04;

/// 本地玩家（自己）的 `entity*` 指针所在位置。
/// 用途：算距离、判断哪个实体是「我自己」。
/// 未验证 → 留 None，代价只是不知道谁是本地玩家（不显示距离、自己也会被画出来）。
pub const LOCAL_PLAYER: Option<usize> = None;

// ---------------------------------------------------------------------------
// 单个玩家实体（playerent）内部的偏移
// ---------------------------------------------------------------------------

/// 头部坐标的 x 分量；Vec3 的 y / z 就在后面各 +4 字节。
/// 我们直接用 `memory::read::<Vec3>()` 一次读 12 字节，所以只记起点就够。
pub const HEAD_POSITION: usize = 0x4;

/// 脚部坐标的 x 分量（同样一次读 12 字节）
pub const FEET_POSITION: usize = 0x28;

/// 血量（i32）。
///
/// 【已实测确认（AssaultCube 1.2.0.2）】
/// * 活人：`100`
/// * 尸体：**`-10`**（注意：不是 0！这一点坑了我们很久）
///
/// 所以“血量 <= 0 就不画”这个规则是有效的（-10 会被涋掉），
/// 但前提是**判定范围不能太严**：按 0~100 过滤会把 -10 当成“偏移错、没读到”，
/// 然后按“没读到就算了，当成活着”处理，尸体就又出来了（详见 `data.rs::health_is_plausible`）。
pub const HEALTH: usize = 0xEC;

/// 【备用】玩家状态。
///
/// 【现在已经不需要它了】
/// 原本准备用它筛尸体，后来实测发现：`HEALTH`（0xEC）足够可靠 ——
/// 活人 100、尸体 -10，直接看血量就行。
/// 这个偏移保留在这里，是作为「血量也不对头」时的备用方案（比如换游戏版本）。
///
/// AC 里这个字段是一组状态码：
/// ```text
///   0 = 活着(CS_ALIVE)   1 = 死亡(CS_DEAD)   2 = 出生中(CS_SPAWNING)
///   3 = 掉线(CS_LAGGED)  4 = 编辑器    5 = 旁观(CS_SPECTATE)
/// ```
/// 未验证 → None（程序会退回用血量判断，也就是现在实际生效的那套）。
/// 真要填的话：用菜单里的「字段扫描」把活人和尸体对比一下，
/// 或者以 0xEC 为中心在 0xE0~0x110 之间找那个“死亡瞬间变 1”的字段。
pub const STATE: Option<usize> = None;

/// AC 的 MAXCLIENTS：实体数量上限。
/// 用来做合理性检查：读到的数量超过它就说明偏移错了，直接跳过这一帧。
pub const MAX_PLAYERS: usize = 32;
